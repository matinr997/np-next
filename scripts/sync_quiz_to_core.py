#!/usr/bin/env python3
"""Rebuild the legacy QUIZ block inside lib/player-core.js, keyed by video id.

The player has two quiz paths:

  1. quizzes/<video-id>.json  — per-video, generated by scripts/gen_quiz.py.
     The player loads this first (loadQuizJson) and it wins.
  2. the embedded `const QUIZ=[...]` fallback — used only when (1) is missing.

The fallback used to be sliced by the video's INDEX in the VIDEOS array:

    QUIZ.slice(idx*3, idx*3+3)      // idx = VIDEOS.indexOf(cur)

That is silently wrong whenever VIDEOS is reordered or new videos are added:
the quiz of one video gets shown under another video's title, and the newest
videos fall off the end of the array and get an empty quiz. Both happened here
(4 videos were added and the list was re-sorted by publish date).

This script rewrites the fallback as an id-keyed map, so a question can only
ever be shown with the video it was written for:

    const QUIZ_BY_VIDEO = {"<video-id>": [ ...questions... ], ...};

and patches renderQuizLegacy() to look up by id instead of by index. It also
adds the `qNone` UI string used when a video genuinely has no quiz yet.

The id -> questions mapping is not derivable from the current VIDEOS order (that
is the bug), so it is read from data/quiz_map.json, which stores the questions
already grouped per video id.

Usage:
    python3 scripts/sync_quiz_to_core.py            # rewrite the block
    python3 scripts/sync_quiz_to_core.py --check    # verify only, no writes
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, 'lib', 'player-core.js')
MAP = os.path.join(ROOT, 'data', 'quiz_map.json')

START = 'const QUIZ_BY_VIDEO = '
OLD_START = 'const QUIZ=['

Q_NONE_EN = "No quiz for this lesson yet."
Q_NONE_FA = "برای این درس هنوز آزمونی آماده نشده است."


def load_grouped():
    """Return {video_id: [questions]} from data/quiz_map.json."""
    with open(MAP, encoding='utf-8') as fh:
        raw = json.load(fh)
    if not isinstance(raw, dict):
        raise SystemExit('data/quiz_map.json must be an object keyed by video id.')
    return {k: v for k, v in raw.items() if isinstance(v, list) and v}


def build(groups):
    """One object literal: {"id": [questions], "id2": [questions]}"""
    body = json.dumps(groups, ensure_ascii=False, indent=1)
    return START + body + ';\n'


def patch_render(core):
    """Point renderQuizLegacy() at the id-keyed map."""
    # The shipped file wraps this function across several lines, so match the
    # statement rather than the whole function header.
    old = "  const idx=VIDEOS.indexOf(cur), qs=QUIZ.slice(idx*3,idx*3+3);"
    new = ("  const qs=(typeof QUIZ_BY_VIDEO!=='undefined'&&cur)?(QUIZ_BY_VIDEO[cur.id]||[]):[];\n"
           "  if(!qs.length){ box.innerHTML=`<div class=\"qscore\">${T('qNone')}</div>`; return; }")
    if old in core:
        return core.replace(old, new), True
    if 'QUIZ_BY_VIDEO[cur.id]' in core:
        return core, False
    return core, None


def patch_uistr(core):
    """Add the qNone string to both locales."""
    changed = False
    # Keep the anchor key: replace "en:{heroH:" with "en:{qNone:'..',heroH:".
    for anchor, value in (("en:{heroH:", "en:{qNone:'%s',heroH:" % Q_NONE_EN),
                           ("fa:{heroH:", "fa:{qNone:'%s',heroH:" % Q_NONE_FA)):
        if anchor in core and "qNone:" not in core.split(anchor, 1)[1][:400]:
            core = core.replace(anchor, value, 1)
            changed = True
    return core, changed


def replace_block(core, groups):
    """Swap the embedded QUIZ array for the id-keyed map."""
    block = build(groups)
    if START in core:
        i = core.index(START)
        j = core.index(';\n', i) + 2
        return core[:i] + block + core[j:]
    if OLD_START in core:
        i = core.index(OLD_START)
        j = core.index('];', i) + 2
        return core[:i] + block + core[j:]
    raise SystemExit('no embedded QUIZ block found in lib/player-core.js')


def main():
    check_only = '--check' in sys.argv
    groups = load_grouped()
    src = open(CORE, encoding='utf-8').read()

    src = replace_block(src, groups)
    src, patched = patch_render(src)
    src, ui_changed = patch_uistr(src)

    if check_only:
        # "already patched" counts as a pass, as long as the id-keyed lookup
        # and the qNone string are both in place.
        ok = 'QUIZ_BY_VIDEO[cur.id]' in src and 'qNone:' in src and 'QUIZ.slice(idx*3' not in src
        print('quiz map: %d videos | renderQuizLegacy: %s | qNone: %s'
              % (len(groups),
                 'ok' if 'QUIZ_BY_VIDEO[cur.id]' in src else 'MISSING',
                 'ok' if 'qNone:' in src else 'MISSING'))
        return 0 if ok else 1

    open(CORE, 'w', encoding='utf-8').write(src)
    rc = subprocess.run(['node', '--check', CORE], capture_output=True, text=True)
    print('player-core.js: QUIZ_BY_VIDEO with %d videos | renderQuizLegacy: %s | qNone: %s'
          % (len(groups),
             'patched' if patched else ('already' if patched is False else 'NOT FOUND'),
             'added' if ui_changed else 'already'))
    print('node --check rc=%d %s' % (rc.returncode, rc.stderr[:300]))
    return rc.returncode


if __name__ == '__main__':
    sys.exit(main())
