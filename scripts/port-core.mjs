// Auto-ports the extracted vanilla logic (extract_logic.js) into a React-friendly
// ES module: lib/player-core.js. Keeps the original code verbatim inside a scope,
// but rewires the few globals (SUBS, UIL, plan-gating, account) to injected values.
import fs from 'node:fs';
import path from 'node:path';

const SCRATCH = process.env.SCRATCH || '/Users/matin/.hermes/profiles/brain-hub/cache/scratch';
const ROOT = '/Users/matin/Documents/02-Areas/Nurseplus+/nurseplus-web';

let logic = fs.readFileSync(path.join(SCRATCH, 'extract_logic.js'), 'utf8');

// ---- 1. inject SUBS as a lazy-loading stub (fetches public/subs/{id}.json on demand)
const subsStub = `const SUBS = {}; let _subsLoaded = {};
async function loadSubs(id){ if(_subsLoaded[id]) return; _subsLoaded[id]=true;
  try{ const r=await fetch('/subs/'+id+'.json'); if(r.ok){ SUBS[id]=await r.json(); } }catch(e){}
  // let the UI re-render the transcript/subtitle bar once data lands
  try{ if(typeof cur!=='undefined'&&cur&&cur.id===id){ renderDetail(); subBoot(); } }catch(e){} }`;
// replace: const SUBS = {...huge inline...};  → lazy stub
const subStart = logic.indexOf('const SUBS =');
if (subStart < 0) throw new Error('SUBS block not found');
const subEnd = logic.indexOf('\n', logic.indexOf('};', subStart)); // end of the object literal line(s)
const subClose = logic.indexOf('};', subStart);
const realSubEnd = logic.indexOf('\n', subClose);
logic = logic.slice(0, subStart) + subsStub + logic.slice(realSubEnd + 1);

// ---- 2. UIL: keep, but default from injected window.__NP_LANG (no localStorage hijack)
logic = logic.replace(
  /let UIL='en';\s*try\{UIL=localStorage\.getItem\('np_uilang'\)\|\|'en';\}catch\(e\)\{UIL='en'\}/,
  "let UIL=(typeof window!=='undefined'&&window.__NP_LANG)||'fa';"
);

// ---- 3. account: real logged-in user via injected window.__NP_USER (not localStorage fake)
logic = logic.replace(
  /function accUser\(\)\{[^}]*\}/,
  "function accUser(){try{return (window.__NP_USER&&window.__NP_USER.name)||'';}catch(e){return '';}}"
);
// accSync shows plan badge too
logic = logic.replace(
  /function accSync\(\)\{[^}]*\}/,
  "function accSync(){var b=document.getElementById('accBtn');if(!b)return;var u=accUser();b.textContent=u?('👤 '+u):('👤 '+T('login'));var pb=document.querySelector('.pro-badge');if(pb){try{var pr=(window.__NP_USER&&window.__NP_USER.plan)||'free';pb.style.display=(pr==='premium')?'inline-block':'none';}catch(e){}}}"
);

// ---- 4. plan gating: renderDetail shows lockbox for panes when not premium
logic = logic.replace(
  /function renderDetail\(\)\{\s*renderDetailHead\(\);/,
  "function renderDetail(){\n  var _plan=(window.__NP_PLAN)||'free';\n  renderDetailHead();"
);
// gate pane1 (transcript)
logic = logic.replace(
  /document\.getElementById\('pane1'\)\.innerHTML = renderTrans\(v\); \/\*SUB\*\//,
  "document.getElementById('pane1').innerHTML = (_plan==='premium') ? renderTrans(v) : `<div class=\"lockbox\">${T('lockTr')}<br><a href=\"/premium\">${T('upgrade')}</a></div>`; /*SUB*/"
);
// gate pane2 (notes) and pane3 (quiz) — find their assignments
const notesGate = "document.getElementById('pane2').innerHTML = (_plan==='premium') ? renderNotes() : `<div class=\"lockbox\">${T('lockNotes')}<br><a href=\"/premium\">${T('upgrade')}</a></div>`;";
const quizGate = "document.getElementById('pane3').innerHTML = (_plan==='premium') ? renderQuiz() : `<div class=\"lockbox\">${T('lockQuiz')}<br><a href=\"/premium\">${T('upgrade')}</a></div>`;";
logic = logic.replace(/document\.getElementById\('pane2'\)\.innerHTML = renderNotes\(\);/, notesGate);
logic = logic.replace(/document\.getElementById\('pane3'\)\.innerHTML = renderQuiz\(\);/, quizGate);

// ---- 5. boot: export a mount() that wires handlers + starts the app
const mount = `
/* ===== React mount hook ===== */
export function mount(root){
  window.__NP_LANG = root.dataset.lang || 'fa';
  try{ root.innerHTML = SKELETON_HTML; }catch(e){}
  // re-bind the global scope the inline onclick handlers need
  const g = (typeof window!=='undefined')?window:{};
  g.openDetail=openDetail; g.showList=showList; g.seek=seek; g.ytGo=ytGo;
  g.ans=ans; g.addNote=addNote; g.delNote=delNote; g.setNLang=setNLang; g.setQLang=setQLang;
  g.accToggle=accToggle; g.ckOk=ckOk; g.applyTabs=applyTabs;
  g.onYouTubeIframeAPIReady=onYouTubeIframeAPIReady;
  applyUI(); ckShow(); accSync();
  if(g.__NP_ONMOUNT) g.__NP_ONMOUNT();
  return ()=>{ try{ if(typeof subTimer!=='undefined'&&subTimer) clearInterval(subTimer); }catch(e){}
               try{ if(typeof ctTimer!=='undefined'&&ctTimer) clearInterval(ctTimer); }catch(e){}
               try{ pvKill(); }catch(e){} try{ if(ytP&&ytP.destroy) ytP.destroy(); }catch(e){} };
}
`;

// prefix: import skeleton + expose helpers the code expects as module-level
const header = `// AUTO-GENERATED by scripts/port-core.mjs — do not edit by hand.\n` +
  `import { SKELETON_HTML } from './skeleton.js';\n` +
  `const T = (typeof globalThis.__T === 'function') ? globalThis.__T : undefined;\n`;

// The original defines its own T later; drop the guard (keep original T).
const out = header + logic + '\n' + mount;
fs.writeFileSync(path.join(ROOT, 'lib/player-core.js'), out);
console.log('wrote lib/player-core.js', out.length, 'bytes');
// report remaining inline globals for sanity
const g = ['VIDEOS','CATS','QUIZ','UISTR','SUBS','cur','ytP','UIL'];
for (const k of g) console.log(k, out.includes(k) ? 'ok' : 'MISSING');
